// Aliens（λ の二分探索 / ラグランジュ緩和）
//
// 「ちょうど k 個使う」という制約を、ペナルティ λ に置き換えて
// 外す。外した方は普通に解けるようになる。
//
//   最小化: G(λ) = min( F(k) + λk )  ->  F(w) = G(λ) - λw
//   最大化: G(λ) = max( F(k) - λk )  ->  F(w) = G(λ) + λw
//
// 目的でやったことの逆を最後にやるだけ。どちらも λ を増やすと
// 選ばれる個数が減るので、二分探索の向きは同じ
//
// 使える条件（1 を破ると黙って違う値を返す。警告は出ない）
//   1. F(k) が凸
//        最小化 -> 差分 F(k+1)-F(k) が広義単調増加
//        最大化 -> 差分が広義単調減少
//        全域木・森なら保証される。DP なら小さいケースで
//        F(k) を全探索して差分の単調性を assert で確かめる
//   2. f の中で λ を 最小化なら足す / 最大化なら引く
//   3. 同点のとき個数が最大になる側にタイブレークする
//        これを忘れると「ちょうど k」が作れない
//   4. [lo, hi] は十分広く。1 回の値域が C なら [-C-1, C+1]
//   5. 呼ぶ前に両端で k が達成可能か確かめる
//        f(lo).second < k か f(hi).second > k なら -1
//
// 「k 個以下」なら λ >= 0 に制限するだけでよく、凸は要らない。
// 凸が必須なのは「ちょうど」のときだけ
//
// 同じ傾きが並ぶ（平坦部）のは対応済み。その区間の k は全部
// 同じ直線に乗るので F(k) = G(λ) - λk がそのまま成り立つ
//
// 対応していないもの
//   凸でない / λ が整数で足りない（実数コスト）/ 構成を出す
//   / オーバーフロー
//
// f の中で毎回ソートし直さないこと。λ は片方の群を平行移動
// させるだけなので、2 群を 1 回ずつソートしてマージする
//
// f(lam) -> {最適値, 使った個数}
//   個数は「その λ での最適解のうち最大のもの」を返すこと。
//   任意に選んではいけない。二分探索は
//     b(best) >= k かつ b(best+1) < k
//   で k を最適区間に挟んでいて、b が最大個数でないと
//   この挟み撃ちが成立しない。
//   値の方は同点ならどれも同じなので制約なし
// 返り値: ちょうど k 個のときの最適値
template<class F> ll aliens(ll lo, ll hi, ll k, bool mx, F f) {
   ll best = lo;
   while(lo <= hi) {
      ll mid = lo + (hi - lo) / 2;
      if(f(mid).second >= k) best = mid, lo = mid + 1;
      else hi = mid - 1;
   }
   auto [v, c] = f(best);
   return mx ? v + best * k : v - best * k;
}
